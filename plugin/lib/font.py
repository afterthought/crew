def glyph(ch):
    """The rows of a character, top to bottom, each a byte whose six high bits are its pixels, left to right."""
    h = GLYPHS.get(ch) or GLYPHS["?"]
    return [int(h[i:i + 2], 16) for i in range(0, 2 * HEIGHT, 2)]
